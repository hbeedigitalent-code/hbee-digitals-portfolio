/**
 * Stylised world map data for the About "reach" visual (Phase 15.1).
 *
 * Hand-simplified land outlines in [longitude, latitude] — decorative, not
 * survey-accurate. They are rendered as a clip path over a dot pattern, so
 * the map costs a handful of paths, not thousands of nodes.
 *
 * Projection: equirectangular, x = lon + 180, y = 75 − lat (lat 75°N → y 0).
 */

