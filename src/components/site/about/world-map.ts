/** A route from Abuja that bows upward (or eastward when it runs north–south). */
export function routePath(to: LonLat) {
  const [x1, y1] = project(ABUJA)
  const [x2, y2] = project(to)
  const dx = x2 - x1
  const dy = y2 - y1
  const len = Math.hypot(dx, dy)
  let px = -dy / len
  let py = dx / len
  if (py > 0) [px, py] = [-px, -py]
  if (Math.abs(py) < 0.15 && px < 0) [px, py] = [-px, -py]
  const bow = len * 0.28
  const cx = (x1 + x2) / 2 + px * bow
  const cy = (y1 + y2) / 2 + py * bow
  const f = (n: number) => +n.toFixed(2)
  return `M${f(x1)} ${f(y1)}Q${f(cx)} ${f(cy)} ${f(x2)} ${f(y2)}`
}
